void
test_xchacha20_init_destroy(void) {
	xchacha20_h state;

	CU_ASSERT_PTR_NOT_NULL(state = xchacha20_init(key, iv, 0));
	CU_ASSERT_EQUAL(xchacha20_destroy(&state), 0);
	CU_ASSERT_PTR_NULL(state);

	return;
}

void
test_xchacha20_param(void) {
	CU_ASSERT_EQUAL(xchacha20_parameter_length(XCHACHA20_KEY), 32);
	CU_ASSERT_EQUAL(xchacha20_parameter_length(XCHACHA20_IV), 24);
	CU_ASSERT_EQUAL(xchacha20_parameter_length(100), 0);

	return;
}

void
test_xchacha20_rand32(void) {
	xchacha20_h state;
	uint32_t test_val, rand_val;
	int i, j;

	/*  */
	state = xchacha20_init(key, iv, 0);

	/*  */
	for (i = 0; i < BLK_CNT; ++i) {
		for (j = 0; j < (BLK_LEN / 4); ++j) {
			test_val = ((uint32_t) (block[i][j * 4]) |
			    (uint32_t) (block[i][j * 4 + 1]) <<  8 |
			    (uint32_t) (block[i][j * 4 + 2]) << 16 |
			    (uint32_t) (block[i][j * 4 + 3]) << 24);
			rand_val = xchacha20_rand32(state);
			CU_ASSERT_EQUAL(rand_val, test_val);
		}
	}

	/*  */
	xchacha20_destroy(&state);

	return;
}

